export type ReadinessCode =
  | "unsupported"
  | "installation"
  | "timeout"
  | "cache"
  | "storage"
  | "build"
  | "update";
export type ReadinessReport = {
  ready: boolean;
  version?: string;
  contractVersion?: number;
  missingFiles?: string[];
  error?: string;
  code?: ReadinessCode;
  durationMs?: number;
};
export type ReadinessProgress = {
  phase: "installing" | "checking" | "repairing" | "updating" | "ready";
  completed?: number;
  total?: number;
  version?: string;
};
export class OfflineReadinessError extends Error {
  constructor(
    public readonly code: ReadinessCode,
    message: string,
    public readonly report?: ReadinessReport,
  ) {
    super(message);
    this.name = "OfflineReadinessError";
  }
}

/** Bound non-abortable Cache API and worker operations too. */
export function untilAborted<T>(
  work: Promise<T>,
  signal: AbortSignal,
): Promise<T> {
  return new Promise((resolve, reject) => {
    const abort = () => reject(signal.reason);
    if (signal.aborted) {
      void work.catch(() => {});
      abort();
      return;
    }
    signal.addEventListener("abort", abort, { once: true });
    work
      .then(resolve, reject)
      .finally(() => signal.removeEventListener("abort", abort));
  });
}
type AssetManifest = { version: string; assets: string[]; shell?: string };
export function validateAssetManifest(
  value: unknown,
  version: string,
): AssetManifest {
  const manifest = value as Partial<AssetManifest> | null;
  if (
    !manifest ||
    `miniros-${manifest.version}` !== version ||
    !Array.isArray(manifest.assets) ||
    manifest.assets.length === 0 ||
    manifest.assets.some(
      (path) =>
        typeof path !== "string" ||
        path.includes("..") ||
        !/^\/_next\/static\/[\w/().\[\]-]+\.(js|css|woff2?)$/.test(path),
    ) ||
    (manifest.shell !== undefined && manifest.shell !== "/pwa-shell.html")
  )
    throw new OfflineReadinessError(
      "build",
      "Offline files belong to another app version. Checking for a safe app update…",
    );
  return manifest as AssetManifest;
}
/** New builds carry a marker; old Next 15 shells carry the Flight build ID. */
export function shellBuild(html: string): string | undefined {
  const marker = html.match(
    /<meta name="miniros-build" content="([\w-]+)"\s*\/?\s*>/,
  )?.[1];
  const flight = html.replaceAll('\\"', '"').match(/"b":"([\w-]+)"/)?.[1];
  // Reject a marker added to HTML generated by a different Next build.
  if (marker && flight && marker !== flight) return undefined;
  return marker ?? flight;
}
function cacheFailure(failure: unknown, report: ReadinessReport): never {
  if (failure instanceof OfflineReadinessError)
    throw failure.report
      ? failure
      : new OfflineReadinessError(failure.code, failure.message, report);
  report = {
    ...report,
    error:
      failure instanceof Error ? failure.message : "Offline cache unavailable",
  };
  if (failure instanceof DOMException && failure.name === "QuotaExceededError")
    throw new OfflineReadinessError(
      "storage",
      "Device storage is full. Free space outside MINIROS, then retry. Keep this app's saved data.",
      report,
    );
  throw new OfflineReadinessError(
    "cache",
    "Offline files couldn't be repaired. Check your connection, keep MINIROS open, then retry.",
    report,
  );
}
/** These responses are verified public files, never authenticated HTML or APIs. */
function publicCacheResponse(response: Response) {
  const headers = new Headers(response.headers);
  // Older workers use Cache.match without ignoreVary. Normalize the saved public
  // response so they can also verify it after Safari supplies transport headers.
  headers.delete("vary");
  headers.delete("content-encoding");
  headers.delete("content-length");
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}
export async function repairOfflineCache(
  report: ReadinessReport,
  signal: AbortSignal,
  progress: (value: ReadinessProgress) => void,
) {
  const version = report.version;
  if (!version || !/^miniros-[\w-]+$/.test(version))
    throw new OfflineReadinessError(
      "build",
      "This app version cannot identify its offline files. A safe app update is required.",
      report,
    );
  try {
    const cache = await untilAborted(caches.open(version), signal);
    const saved = await untilAborted(
      cache.match("/pwa-assets.json", { ignoreVary: true }),
      signal,
    );
    let manifest: AssetManifest;
    // Legacy manifests omit the version. Only a matching network manifest may repair them.
    const value = saved
      ? await untilAborted(
          saved.json().catch(() => undefined),
          signal,
        )
      : undefined;
    let cached: AssetManifest | undefined;
    if (value?.version) {
      try {
        cached = validateAssetManifest(value, version);
      } catch {
        /* Repair an invalid cached manifest from this build's network manifest. */
      }
    }
    // New workers reject truncated manifests against their embedded asset list.
    if (report.code === "cache") cached = undefined;
    if (cached) manifest = cached;
    else {
      const response = await untilAborted(
        fetch("/pwa-assets.json", {
          cache: "no-store",
          signal,
        }),
        signal,
      );
      if (!response.ok || response.redirected)
        throw new Error("Asset list unavailable");
      manifest = validateAssetManifest(
        await untilAborted(response.json(), signal),
        version,
      );
    }
    const paths = [
      ...new Set([
        "/offline",
        "/manifest.webmanifest",
        "/icons/icon-192.png",
        ...manifest.assets,
      ]),
    ];
    const missing: string[] = [];
    for (const path of paths) {
      const response = await untilAborted(
        cache.match(path, { ignoreVary: true }),
        signal,
      );
      if (!response?.ok) missing.push(path);
      else if (
        path === "/offline" &&
        shellBuild(await untilAborted(response.clone().text(), signal)) !==
          manifest.version
      )
        missing.push(path);
      else if (response.headers.has("vary"))
        await untilAborted(
          cache.put(path, publicCacheResponse(response)),
          signal,
        );
    }
    let completed = 0;
    report = { ...report, missingFiles: missing };
    if (cached && missing.length) {
      // An immutable cached manifest identifies the missing hashes, but shared
      // URLs (shell, icon, web manifest) must still come from this deployment.
      const response = await untilAborted(
        fetch("/pwa-assets.json", {
          cache: "no-store",
          signal,
        }),
        signal,
      );
      if (!response.ok || response.redirected)
        throw new OfflineReadinessError(
          "build",
          "This app's offline asset list is unavailable. Checking for a safe app update…",
          report,
        );
      validateAssetManifest(
        await untilAborted(response.json(), signal),
        version,
      );
    }
    progress({ phase: "repairing", completed, total: missing.length, version });
    // Four downloads avoid a burst of 100+ simultaneous requests on iPhones.
    for (let index = 0; index < missing.length; index += 4) {
      const batch = await Promise.allSettled(
        missing.slice(index, index + 4).map(async (path) => {
          signal.throwIfAborted();
          const response = await untilAborted(
            fetch(path === "/offline" ? (manifest.shell ?? path) : path, {
              cache: "no-store",
              signal,
            }),
            signal,
          );
          if (response.status === 404 || response.status === 410)
            throw new OfflineReadinessError(
              "build",
              "Saved files are no longer available for this app version. Checking for a safe app update…",
              { ...report, missingFiles: missing },
            );
          if (
            !response.ok ||
            response.redirected ||
            (path !== "/offline" &&
              response.headers.get("content-type")?.includes("text/html"))
          )
            throw new Error(`Offline download failed: ${path}`);
          if (
            path === "/offline" &&
            shellBuild(await untilAborted(response.clone().text(), signal)) !==
              manifest.version
          )
            throw new OfflineReadinessError(
              "build",
              "The app changed while downloading offline files. A safe app update is required.",
              report,
            );
          signal.throwIfAborted();
          await untilAborted(
            cache.put(path, publicCacheResponse(response)),
            signal,
          );
          progress({
            phase: "repairing",
            completed: ++completed,
            total: missing.length,
            version,
          });
        }),
      );
      // Settle the whole batch before an update or retry can start another one.
      for (const item of batch)
        if (item.status === "rejected") throw item.reason;
    }
    // Publish the manifest last. A failed batch never commits a readiness marker.
    for (const path of paths) {
      if (
        !(await untilAborted(cache.match(path, { ignoreVary: true }), signal))
          ?.ok
      )
        throw new Error(`Offline file still missing: ${path}`);
    }
    await untilAborted(
      cache.put(
        "/pwa-assets.json",
        new Response(JSON.stringify(manifest), {
          headers: { "Content-Type": "application/json" },
        }),
      ),
      signal,
    );
  } catch (failure) {
    if (signal.aborted) throw signal.reason;
    cacheFailure(failure, report);
  }
}
